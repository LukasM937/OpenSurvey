"""
Closed-question option handling shared by server.py (intake) and aggregator.py.

allowed_options.json (generated by tools/gen_allowed_options.mjs) maps, per
radio/check question, every string the UI can submit (German + all
translations) to the canonical German option. Intake rejects anything else and
folds translations onto the German option; the aggregator applies the same
fold to stored records so that e.g. "Bavaria" and "Bayern" count as one region.
"""

import json
from pathlib import Path
from typing import Any

# Free-text questions (schema type "text"). Never published verbatim anywhere.
FREE_TEXT_QUESTIONS = frozenset({"Q052", "Q064", "Q142", "Q143", "Q151", "Q178", "Q182", "Q183"})
KA_VALUE = "__ka__"
SKIPPED_VALUE = "__skipped__"

OPTIONS_FILE = Path(__file__).with_name("allowed_options.json")

try:
    OPTION_MAP: dict[str, dict[str, str]] = json.loads(OPTIONS_FILE.read_text(encoding="utf-8"))
except Exception as exc:  # fail closed: without the allowlist intake must not accept free strings
    raise RuntimeError(f"allowed_options.json konnte nicht geladen werden: {OPTIONS_FILE}") from exc


def canonical_option(qid: str, value: Any) -> Any:
    """Return the canonical German option for value, or value itself if the
    question is not a closed question or the value is unknown."""
    mapping = OPTION_MAP.get(qid)
    if mapping is None:
        return value
    if isinstance(value, str):
        return mapping.get(value, value)
    if isinstance(value, list):
        return [mapping.get(v, v) if isinstance(v, str) else v for v in value]
    return value


def sanitize_closed(qid: str, value: Any) -> Any:
    """Fold a stored value of a closed question onto canonical options; values
    that are not a valid option (legacy/poisoned records) become "keine Angabe"
    (single choice) or are dropped (multiple choice)."""
    mapping = OPTION_MAP.get(qid)
    if mapping is None:
        return value
    valid = set(mapping.values())
    if isinstance(value, list):
        return [v for v in (mapping.get(x, x) for x in value if isinstance(x, str)) if v in valid or v == KA_VALUE]
    if value is None or value == SKIPPED_VALUE or value == KA_VALUE:
        return value
    folded = mapping.get(value) if isinstance(value, str) else None
    return folded if folded is not None else KA_VALUE
